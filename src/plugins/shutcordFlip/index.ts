import { ApplicationCommandInputType, ApplicationCommandOptionType, findOption } from "@api/Commands";
import { Devs } from "@utils/constants";
import definePlugin from "@utils/types";


const FLIP: Record<string, string> = {
    a: "ɐ", b: "q", c: "ɔ", d: "p", e: "ǝ", f: "ɟ", g: "ƃ", h: "ɥ", i: "ᴉ", j: "ɾ", k: "ʞ", l: "l", m: "ɯ",
    n: "u", o: "o", p: "d", q: "b", r: "ɹ", s: "s", t: "ʇ", u: "n", v: "ʌ", w: "ʍ", x: "x", y: "ʎ", z: "z",
    "?": "¿", "!": "¡", ".": "˙", ",": "'", "'": ",", "(": ")", ")": "(", "[": "]", "]": "[", "<": ">", ">": "<"
};

export default definePlugin({
    name: "ShutcordFlip",
    description: "/flip turns your text upside down",
    tags: ["Commands", "Fun"],
    authors: [Devs.Shutcord],

    commands: [
        {
            name: "flip",
            description: "Upside down text",
            inputType: ApplicationCommandInputType.BUILT_IN_TEXT,
            options: [
                { name: "text", description: "The text to use", type: ApplicationCommandOptionType.STRING, required: true }
            ],
            execute(args, ctx) {
                const out = [...findOption<string>(args, "text", "").toLowerCase()].map(c => FLIP[c] ?? c).reverse().join("");
                return { content: out };
            }
        }
    ]
});
